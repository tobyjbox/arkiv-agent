import { getOrCreateDescription } from "@arkiv-agent/catalogue";
import { Sparkles } from "lucide-react";

/**
 * AI summary card (design/03-catalogue.md, detail section 2). Server component in its own
 * Suspense boundary: a cached summary renders at once; a new one streams in when ready.
 */
export async function AiSummary({ id }: { id: string }) {
  const state = await getOrCreateDescription(id);
  if (state.status !== "ready") {
    return (
      <div className="rounded-md border border-border-default bg-surface p-5 text-text-secondary">
        No AI summary yet. The schema below is read directly from Arkiv.
      </div>
    );
  }
  const d = state.description;
  return (
    <div className="rounded-md p-5 tint-ai">
      <div className="label flex items-center gap-1.5"><Sparkles size={14} aria-hidden />AI summary</div>
      <p className="mt-2 text-text-primary">{d.summary}</p>
      <p className="mt-1 text-text-primary">Likely use: {d.likelyUse}</p>
      {d.suggestedName && <p className="mt-1 caption text-text-secondary">Suggested name: <span className="font-mono">{d.suggestedName}</span></p>}
      <p className="mt-3 caption text-text-tertiary">Generated by {d.model} from {d.inputs}. Model output; check it against the schema.</p>
    </div>
  );
}

/** Pattern 2 skeleton for the card while a summary is written. */
export function AiSummarySkeleton() {
  return (
    <div className="rounded-md p-5 tint-ai" aria-busy>
      <div className="label flex items-center gap-1.5"><Sparkles size={14} aria-hidden />AI summary</div>
      <div className="mt-3 h-4 w-11/12 rounded-sm bg-raised" />
      <div className="mt-2 h-4 w-2/3 rounded-sm bg-raised" />
      <p className="mt-3 caption text-text-tertiary">Writing a summary…</p>
    </div>
  );
}
